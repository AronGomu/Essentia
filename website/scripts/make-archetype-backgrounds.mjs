import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { homedir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

/** Owner-supplied AI-generated backdrops. Converted once, by hand, then committed.
 *  The sources live outside the repo; `--source-dir` points the run elsewhere. */
export const BACKGROUND_SOURCE_DIR = path.join(homedir(), 'Downloads');
export const BACKGROUND_SOURCES = {
  'burning-abyss': path.join(BACKGROUND_SOURCE_DIR, 'burning-abyss-bg.png'),
  nekroz: path.join(BACKGROUND_SOURCE_DIR, 'nekroz-bg.png'),
};
export const MAX_WIDTH = 2560;
export const WEBP_QUALITY = 80;
export const PROVENANCE_TOOL = `AI-generated by the owner; sharp webp q${WEBP_QUALITY} (max ${MAX_WIDTH} px)`;

if (import.meta.url === `file://${process.argv[1]}`) {
  const repoRoot = new URL('../../', import.meta.url);
  const sourceDirFlagIndex = process.argv.indexOf('--source-dir');
  const sourceDirOverride =
    sourceDirFlagIndex !== -1 ? process.argv[sourceDirFlagIndex + 1] : null;

  const provenancePath = new URL(
    'website/content/art-provenance.json',
    repoRoot,
  );
  const provenance = JSON.parse(await readFile(provenancePath, 'utf8'));

  const outputDir = new URL('website/public/backgrounds/', repoRoot);
  await mkdir(outputDir, { recursive: true });

  const generatedOn = new Date().toISOString().slice(0, 10);

  for (const [slug, defaultSource] of Object.entries(BACKGROUND_SOURCES)) {
    const sourcePath = sourceDirOverride
      ? path.join(sourceDirOverride, path.basename(defaultSource))
      : defaultSource;
    const output = fileURLToPath(new URL(`${slug}.webp`, outputDir));
    await sharp(sourcePath)
      .rotate()
      .resize({ width: MAX_WIDTH, withoutEnlargement: true })
      .webp({ quality: WEBP_QUALITY, effort: 5 })
      .toFile(output);

    const key = `/backgrounds/${slug}.webp`;
    let entry = provenance.art.find((item) => item.key === key);
    if (!entry) {
      entry = { key };
      provenance.art.push(entry);
    }
    // Provenance is public: record the file, never the owner's home path.
    entry.source = `owner-supplied (outside repo): ${path.basename(sourcePath)}`;
    entry.tool = PROVENANCE_TOOL;
    entry.generatedOn = generatedOn;
    process.stdout.write(`${slug}: ${sourcePath} -> ${key}\n`);
  }

  await writeFile(provenancePath, `${JSON.stringify(provenance, null, 2)}\n`);
  process.stdout.write(
    'archetype backgrounds: 2 images written, provenance updated\n',
  );
}
